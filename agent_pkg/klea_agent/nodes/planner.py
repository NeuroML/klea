class Planner(BaseLLMNode[KleaAgentState, PlannerOutput]):
    """Task-path brain for the general path (ADR-0035).

    It writes the immutable goal and creates or revises the evolvable plan.
    ``plan.status`` carries the routing outcome (``in_progress`` |
    ``needs_input`` | ``chat`` | ``unplannable``); there is no separate route
    flag.  A plan is reviewed by placing a ``review`` step (ADR-0051), not by a
    status.  ``chat`` is the exception to the task path: it signals that the
    entry router misclassified a conversational request, and routes back to
    ``RouteDecision`` (which has conversation memory) instead of answering from
    the results.  There is no zero-step "no plan required" bypass: a goal whose
    facts are already known is planned as a ``reasoning`` step, so the
    conclusion reaches the answer-composer through observations.  The Planner
    never answers the user.

    Uses the tool descriptions generated by ``BaseLangGraph._build_tools_info``
    (passed as ``tools_info`` to the constructor).  This keeps the
    available-tools list consistent with ``ToolsPicker`` and the MCP registry.
    """

    model_role = "plan"
    model_defaults: ClassVar[dict[str, Any]] = {
        "temperature": 0.01,
    }
    #: Re-invoke the model with the validation error when it returns a
    #: structurally inconsistent plan (dangling dependencies, a trailing
    #: review, duplicate numbers).  Bounded so the node always returns; 3
    #: gives smaller models a few tries while staying bounded.
    max_validation_retries: ClassVar[int] = 3

    def __init__(
        self,
        logger: logging.Logger,
        label: str,
        llm_models: dict[str, Any],
        memory: bool = False,
        max_automated_plan_revisions: int = 4,
        tools_info: dict[str, dict[str, ToolInfo]] | None = None,
    ):
        """Initialise the planner node.

        :param logger: Logger instance
        :param label: Human-readable label for UI progress display
        :param llm_models: ``{role: LLMModel}`` dict (from ``BaseLangGraph.llm_models``)
        :param memory: Whether to include recent conversation history.  The
            Planner needs prior context (follow-ups and earlier failed plans),
            so the orchestrator passes ``memory=self.memory``.
        :param max_automated_plan_revisions: Automated replans allowed in one
            run (since the initial plan or the last human review) before the
            Planner gives up (deterministic budget).  Human review re-entries
            reset the counter.
        :param tools_info: Per-domain ``ToolInfo`` map from
            ``BaseLangGraph.tools_info`` (built before ``_create_graph``);
            filtered by the run's access level per invocation.
        """
        super().__init__(
            logger=logger,
            label=label,
            llm_models=llm_models,
            output_schema=PlannerOutput,
            memory=memory,
        )
        self.max_automated_plan_revisions = max_automated_plan_revisions
        self._tools_info: dict[str, dict[str, ToolInfo]] = tools_info or {}

    def _disclosed_tools(self, state: KleaAgentState) -> dict[str, dict[str, ToolInfo]]:
        """Return the tool catalogue filtered by the run's access level.

        Access-level filtering (ADR-0037) is the single source for both the
        prompt descriptions and the validation of a step's suggested tools.

        :param state: Current graph state (supplies the access level).
        :returns: Per-domain ``{name: ToolInfo}`` map of disclosed tools.
        """
        access_level = getattr(state, "access_level", DEFAULT_ACCESS_LEVEL)
        tools_info = filter_tools_info(self._tools_info, access_level)
        self.logger.debug(
            f"{access_level = }\n"
            f"disclosed_tools = "
            f"{[name for domain in tools_info.values() for name in domain]}"
        )
        return tools_info

    def _get_tool_descriptions(self, state: KleaAgentState) -> str:
        """Return combined compact tool descriptions from ``_tools_info``.

        Uses ``ToolInfo.short_description`` (name plus docstring, no parameter
        list) so the planner prompt stays small under tiered disclosure
        (ADR-0035); the tool picker carries the full argument detail.  Falls
        back to ``description`` when a short form was not built.  Tools the
        state's ``access_level`` does not permit are excluded (ADR-0037), so
        the planner never plans around a disallowed tool.

        :param state: Current graph state (supplies the access level).
        :returns: Compact descriptions joined into one block.
        """
        tools_info = self._disclosed_tools(state)
        parts = [
            info.short_description or info.description or ""
            for domain_tools in tools_info.values()
            for info in domain_tools.values()
        ]
        return "\n\n".join(parts)

    @staticmethod
    def _render_human_input(state: KleaAgentState) -> str:
        """Render the user's needs_input answers against the steps that asked."""
        asked = {step.step_number: step.needs_input for step in state.plan.step_list}
        lines: list[str] = []
        for step_number, answers in state.human_input.items():
            questions = asked.get(step_number, [])
            for index, answer in enumerate(answers):
                question = questions[index] if index < len(questions) else "(question)"
                lines.append(f"- Step {step_number} Q: {question} A: {answer}")
        return "\n".join(lines)

    @override
    def _get_prompt_variables(self, state: KleaAgentState, ctx: Any) -> dict:
        """Format prompt with the query, current plan state and tool catalogue.

        The conditional feedback fields are composed into one optional
        ``feedback_block`` so the prompt omits them entirely when there is
        nothing to say (prompt conventions).  Superseded plan versions are
        rendered separately as ``previous_plans_block`` so a replan can see
        and avoid approaches that already failed.  On a ``continue`` intent
        the bounded ``continuation_evidence`` is rendered as ``previous_work``.
        """
        goal_text = state.goal.goal or "(not set)"
        if state.goal.success_criteria:
            goal_text += f"\nSuccess criteria: {state.goal.success_criteria}"
        feedback_block = "\n\n".join(
            section
            for section in (
                self._optional_section("Review feedback", state.human_feedback),
                self._optional_section("User input", self._render_human_input(state)),
                self._optional_section("Replan reason", state.replan_reason),
                self._optional_section("Validation feedback", ctx.validation_feedback),
            )
            if section
        )
        previous_work = ""
        if state.route.route == "continue" and state.continuation_evidence is not None:
            previous_work = self._optional_section(
                "Previous work (evidence for this continuation)",
                state.continuation_evidence.render(),
            )
        return {
            "query": state.query,
            "goal": goal_text,
            "plan": state.plan.render(),
            "previous_plans_block": self._optional_section(
                "Previous plan versions (abandoned)", state.previous_plans_text()
            ),
            "previous_work": previous_work,
            "feedback_block": feedback_block,
            "discovery": state.discovery_persistent.render(),
            "observations": state.observations_text(),
            "tools_description": self._get_tool_descriptions(state),
        }

    def _tool_availability_errors(
        self,
        step: StepSchema,
        available: set[str],
        configured: set[str],
        access_level: str,
    ) -> list[str]:
        """Return errors for a tool step that names unavailable tools.

        A tool step is only executable when its named tools are disclosed at
        the run's access level.  With no catalogue at all the picker cannot
        bind or dispatch anything (and would retry forever after skipping), so
        the step is rejected before it reaches the picker.

        :param step: The tool step to check.
        :param available: Names disclosed at the run's access level.
        :param configured: All configured tool names (before filtering).
        :param access_level: The active access level (for the message).
        :returns: Human-readable errors; empty when every tool is available.
        """
        if not self._tools_info:
            return [
                (
                    f"step {step.step_number} is a tool step but no tools are "
                    "available; plan a reasoning step or return unplannable"
                )
            ]
        errors: list[str] = []
        for tool in step.suggested_tools:
            if tool in available:
                continue
            if tool in configured:
                errors.append(
                    f"step {step.step_number} names tool '{tool}', which "
                    f"access level '{access_level}' does not permit"
                )
            else:
                errors.append(
                    f"step {step.step_number} names unknown tool '{tool}'; "
                    "use only tools from the available tools list"
                )
        return errors

    @override
    def _validate_result(
        self, result: PlannerOutput, state: KleaAgentState, ctx: Any
    ) -> str | None:
        """Reject a structurally inconsistent or contradictory plan.

        The Planner is the sole plan author; code does not repair its output.
        An inconsistent plan is retried with the errors exposed to the prompt
        as ``validation_feedback``.  Checks:

        * ``status == "unplannable"`` must not carry steps;
        * structural plan consistency (:meth:`PlanSchema.validate_plan`);
        * ``kind``/tool consistency: a ``tool`` step names at least one tool,
          a ``reasoning`` step names none -- unless the step is **blocked** (it
          has ``needs_input`` questions), since a blocked step is a draft that
          is not executed and need not yet be runnable;
        * every named tool must be disclosed at the run's ``access_level``.  A
          tool step is invalid when the catalogue is empty (no tools are
          available to bind or dispatch) or when it names a tool that is
          unknown or filtered out by ``read_only``;
        * a ``review`` step must gate pending work: it must have at least one
          pending non-review step after it (a trailing review gates nothing);
        * ``needs_input`` status must be accompanied by at least one blocked
          step (a question to ask);
        * an ``in_progress`` plan must have at least one step (there is no
          zero-step "already known" bypass).

        ``chat`` is a routing signal, not a task: it must carry no steps and
        needs no goal (the entry router writes the reply from conversation
        history).  A task whose facts are already known instead plans a
        ``reasoning`` step, so the conclusion reaches the answer-composer
        through observations.
        """
        if not isinstance(result, PlannerOutput):
            return None
        errors: list[str] = []
        plan = result.plan
        if plan.status == "unplannable" and plan.step_list:
            errors.append(
                "status is 'unplannable' but steps were returned; "
                "return no steps or set a runnable status"
            )
        if plan.status == "in_progress" and not plan.step_list:
            errors.append(
                "an in_progress plan must have at least one step; if the "
                "facts are already known, plan a single reasoning step to "
                "synthesise them"
            )
        if plan.status == "chat" and plan.step_list:
            errors.append(
                "status is 'chat' but steps were returned; chat is a "
                "conversational route with no plan - return no steps, or use a "
                "runnable status"
            )
        if plan.step_list:
            access_level = getattr(state, "access_level", DEFAULT_ACCESS_LEVEL)
            disclosed = self._disclosed_tools(state)
            available = {name for domain in disclosed.values() for name in domain}
            configured = {
                name for domain in self._tools_info.values() for name in domain
            }
            errors.extend(plan.validate_plan())
            for step in plan.step_list:
                if step.needs_input:
                    # A blocked step is a draft; it need not be runnable yet.
                    continue
                if step.kind == "review":
                    # A review step is a human checkpoint (ADR-0051): it names
                    # no tools and is not executed, but must describe what the
                    # user is reviewing.
                    if not step.description.strip():
                        errors.append(
                            f"step {step.step_number} is a review step but has "
                            "no description"
                        )
                    if step.suggested_tools:
                        errors.append(
                            f"step {step.step_number} is a review step but names tools"
                        )
                    # A review only approves work that runs *after* it.  A
                    # review with no pending non-review step after it gates
                    # nothing -- it would just pause before the answer -- so it
                    # is rejected (the run resumes to the next pending step).
                    if not any(
                        other.kind != "review"
                        and other.status == "pending"
                        and other.step_number > step.step_number
                        for other in plan.step_list
                    ):
                        errors.append(
                            f"step {step.step_number} is a review step with no "
                            "pending work after it; a review only approves the "
                            "steps that run after it - remove it, or add the "
                            "work it should gate"
                        )
                    continue
                if step.kind == "tool":
                    if self._tools_info and not step.suggested_tools:
                        errors.append(
                            f"step {step.step_number} is a tool step but names no tool"
                        )
                    errors.extend(
                        self._tool_availability_errors(
                            step, available, configured, access_level
                        )
                    )
                if step.kind == "reasoning" and step.suggested_tools:
                    errors.append(
                        f"step {step.step_number} is a reasoning step but names tools"
                    )
        if plan.status == "needs_input" and not any(
            step.needs_input for step in plan.step_list
        ):
            errors.append(
                "status is 'needs_input' but no step has questions; "
                "attach the questions to the blocked step(s)"
            )
        return "; ".join(errors) if errors else None

    @staticmethod
    def _preserved_plan(
        prior: PlanSchema,
        status: Literal["unplannable", "needs_input"],
        version: int,
        review_rounds: int,
        revisions: int,
        *,
        extra_steps: list[StepSchema] | None = None,
    ) -> PlanSchema:
        """Build a terminal/draft plan without discarding the authored steps.

        A failed run (or a pause for guidance) keeps the last plan visible in
        the status pane; only the lifecycle status and counters change.  The
        step objects are preserved as-is, including their statuses.

        :param prior: The plan from the incoming state.
        :param status: Runtime plan status to write.
        :param version: New plan version.
        :param review_rounds: Human feedback rounds.
        :param revisions: Automated revision counter.
        :param extra_steps: Optional steps to append (for a guidance draft).
        :returns: The preserved plan.
        """
        steps = list(prior.step_list)
        if extra_steps:
            steps.extend(extra_steps)
        return PlanSchema(
            step_list=steps,
            status=status,
            plan_version=version,
            human_feedback_rounds=review_rounds,
            automated_plan_revisions=revisions,
        )

    @staticmethod
    def _guidance_step(prior: PlanSchema, reason: str) -> StepSchema:
        """Return a blocked step carrying the budget-exhaustion help question.

        Reusing ``needs_input`` means the ordinary HITL input node handles the
        pause; the step is a draft and is never executed.

        :param prior: The incoming plan (for the next step number).
        :param reason: Last automated replan/tool reason, if any.
        :returns: A blocked guidance step.
        """
        number = max((step.step_number for step in prior.step_list), default=0) + 1
        question = (
            "The automated replan budget is exhausted. "
            f"Last reason: {reason.strip() or 'the plan could not be revised automatically'}. "
            "How should I proceed? "
            "Previous plan versions are noted for your information."
        )
        return StepSchema(
            step_number=number,
            description="Provide guidance to continue",
            success_criteria="The user provides guidance for the next plan.",
            kind="reasoning",
            needs_input=[question],
            status="pending",
        )

    @staticmethod
    def _plan_history_with_prior(state: KleaAgentState) -> list[PlanRevision]:
        """Return plan history with the incoming runnable plan appended.

        The active plan is recorded only when it is a real execution attempt
        being superseded.  Synthetic ``needs_input`` guidance drafts are not
        recorded: they are a pause mechanism, not an approach that failed.

        :param state: The incoming state, before its transient feedback is
            cleared.
        :returns: The FIFO-trimmed history including the prior plan.
        """
        history = list(state.plan_history)
        prior = state.plan
        if (
            prior.status != "in_progress"
            or prior.plan_version <= 0
            or not prior.step_list
        ):
            return history
        reason = state.replan_reason.strip()
        if not reason and state.human_feedback.strip():
            reason = f"Human review: {state.human_feedback.strip()}"
        if not reason and state.human_input:
            reason = "Human supplied answers to blocked steps"
        history.append(
            PlanRevision(
                version=prior.plan_version,
                steps=[step.model_copy(deep=True) for step in prior.step_list],
                abandoned_reason=reason or "plan superseded",
            )
        )
        return trim_plan_history(history)

    @override
    def _update_state(
        self, result: PlannerOutput, state: KleaAgentState, ctx: Any
    ) -> dict[str, Any]:
        """Write the goal (locked) and the plan, trusting the model's plan.

        Design (ADR-0035/ADR-0041): the Planner is the **sole author** of the
        plan, including each step's ``status`` and ``depends_on``.  Code does
        not re-apply completion markers or recompute positions by matching step
        numbers across plans (that positional matching was brittle and corrupt
        on renumbering).  The model is given the prior plan with its ``[DONE]``
        markers and is responsible for carrying completed steps forward;
        ``PlannerOutput`` is validated structurally in :meth:`_validate_result`
        and retried if inconsistent.

        Goal handling (ADR-0035): the Planner is the sole goal writer, but it
        only sets the goal while it is unset, so a replan or review revision
        cannot move the success reference.  A freshly built ``PlanSchema`` is
        written rather than mutating the previous one.  The Planner never
        answers the user -- chat is handled by ``RouteDecision`` and the final
        reply by ``AnswerFromResults``.

        A plan with any blocked step (a step carrying ``needs_input``
        questions) is written as a draft with status ``needs_input`` regardless
        of the model's status; an ``unplannable`` status (or an empty plan)
        fails the run, using ``result.reason`` as the failure explanation; a
        plan with steps maps the remaining statuses to the state plan.
        ``result.reason`` is also recorded with the plan in ``messages`` for
        continuity.

        The incoming runnable plan is appended to ``plan_history`` with the
        reason it was abandoned (replan reason, human review feedback, or
        supplied answers), so later replans can see what already failed.  The
        last evaluator verdict is cleared: it described the plan being
        replaced, and keeping it would leak stale step feedback into the new
        plan.

        ``chat`` is the one status that writes neither a goal nor a plan step:
        it hands the request back to ``RouteDecision`` (which has memory) with
        no plan-history message, so the router's conversation context is not
        polluted by a synthetic planning note.  A task whose facts are already
        known is not special-cased: it plans a ``reasoning`` step, which bridges
        those facts into observations for the answer-composer.
        """
        # The transient human/feedback inputs are consumed on this pass: the
        # prompt just read them, so clear them from state.  The blocked state
        # below is re-derived from the plan the Planner writes.
        update: dict[str, Any] = {
            "human_feedback": "",
            "human_input": {},
            "replan_reason": "",
            "review_progress": "",
            "binding_calls": [],
            "plan_history": self._plan_history_with_prior(state),
            "evaluation": EvaluationSchema(),
        }

        # --- Plan-history counters (durable run signal) -------------------
        # ``plan_version`` increments on every authoring; ``human_feedback_rounds``
        # increments when the Planner processes review feedback; the automated
        # revision counter is the budget and resets on a human review.  These
        # live on the plan (``PlanSchema``) so the answer synthesis can be told
        # the final plan is a settled artifact without the raw feedback.
        prior = state.plan
        version = prior.plan_version + 1
        review_rounds = prior.human_feedback_rounds + (1 if state.human_feedback else 0)

        # If validation retries are exhausted, fail closed rather than
        # accepting the last (still invalid) plan.  Keep the previous plan
        # visible; only the status changes.
        if ctx.validation_feedback:
            reason = f"plan validation failed: {ctx.validation_feedback}"
            self.logger.warning(
                "Plan validation failed; giving up: %s", ctx.validation_feedback
            )
            update["plan"] = self._preserved_plan(
                prior,
                "unplannable",
                version,
                review_rounds,
                prior.automated_plan_revisions,
            )
            update["failure_reason"] = reason
            update["messages_internal"] = [
                *state.messages_internal,
                AIMessage(content=f"Planning failed: {reason}"),
            ]
            return update

        # --- Replan budget (deterministic) -------------------------------
        # Link the counter to the unified replan reason: an entry carrying a
        # ``replan_reason`` is an automated replan (Triage escalation,
        # Evaluator ``need_replan``, or picker failure) and consumes the
        # budget; the first plan and a human review re-entry carry no reason,
        # so they reset it.  Deriving from the reason keeps the two in
        # lockstep - a reason can never be present with a zero counter.
        # The ``in_progress`` status is a belt-and-braces fallback so a path
        # that forgets to set the reason still cannot bypass the budget
        # (logged below).  A human review revision also re-enters with an
        # ``in_progress`` plan (ADR-0051) but carries ``human_feedback``, so it
        # is excluded from the fallback: a revision must not consume the
        # automated-replan budget.
        is_replan = bool(state.replan_reason) or (
            state.plan.status == "in_progress" and not state.human_feedback
        )
        if is_replan and not state.replan_reason:
            self.logger.warning(
                "Planner re-entered with an in_progress plan but no "
                "replan_reason; counting it as a replan"
            )
        revisions = prior.automated_plan_revisions + 1 if is_replan else 0
        if revisions > self.max_automated_plan_revisions:
            reason = (
                state.replan_reason or "the plan could not be revised automatically"
            )
            self.logger.warning(
                "Plan revision budget (%d) exhausted; asking for guidance: %s",
                self.max_automated_plan_revisions,
                reason,
            )
            guidance = self._guidance_step(prior, reason)
            plan = self._preserved_plan(
                prior,
                "needs_input",
                version,
                review_rounds,
                revisions,
                extra_steps=[guidance],
            )
            update["plan"] = plan
            update["messages_internal"] = [
                *state.messages_internal,
                AIMessage(
                    content=(
                        f"Plan (needs_input):\n{plan.render()}\n"
                        f"Questions:\n- Step {guidance.step_number}: "
                        f"{guidance.needs_input[0]}"
                    )
                ),
            ]
            self.logger.debug(f"{update = }")
            return update

        # --- Unplannable: the Planner's explicit signal, or no steps at all
        # (except ``needs_input``/``chat``, which legitimately carry no
        # runnable steps).  'unplannable' with steps is rejected in
        # _validate_result; a non-unplannable status with no steps is a
        # deterministic coercion.
        # Handled before the goal lock so a failed plan does not lock a goal.
        steps = result.plan.step_list
        # --- Chat: the entry router misclassified a conversational request.
        # This is not a task outcome: the request only needs the conversation
        # history, which the Planner does not use to reply.  Return no goal and
        # no steps; the graph routes back to ``RouteDecision`` (memory enabled)
        # and forces it to write the chat response.  A chat status with steps is
        # contradictory; after the validation retries the model could still emit
        # it, so fail closed rather than silently dropping work.
        if result.plan.status == "chat":
            if steps:
                self.logger.warning(
                    "Planner returned chat status with %d step(s); failing closed",
                    len(steps),
                )
                update["plan"] = self._preserved_plan(
                    prior,
                    "unplannable",
                    version,
                    review_rounds,
                    revisions,
                )
                update["failure_reason"] = "planner returned chat status with steps"
                update["messages_internal"] = [
                    *state.messages_internal,
                    AIMessage(content=f"Planning failed: {update['failure_reason']}"),
                ]
                self.logger.debug(f"{update = }")
                return update
            update["plan"] = PlanSchema(
                status="chat",
                plan_version=version,
                human_feedback_rounds=review_rounds,
                automated_plan_revisions=revisions,
            )
            self.logger.debug(f"{update = }")
            return update

        if result.plan.status == "unplannable" or (
            not steps and result.plan.status not in ("needs_input", "chat")
        ):
            update["plan"] = self._preserved_plan(
                prior,
                "unplannable",
                version,
                review_rounds,
                revisions,
            )
            update["failure_reason"] = (
                result.reason
                or "planner could not produc a plan with the available information"
            )
            update["messages_internal"] = [
                *state.messages_internal,
                AIMessage(content=f"Planning failed: {update['failure_reason']}"),
            ]
            self.logger.debug(f"{update = }")
            return update

        # Goal lock: write only while unset.
        if not state.goal.goal and result.goal.goal:
            update["goal"] = result.goal
        elif (
            state.goal.goal and result.goal.goal and result.goal.goal != state.goal.goal
        ):
            self.logger.warning(
                "Planner proposed a different goal; keeping the fixed goal (ADR-0035)"
            )

        # A step with questions is blocked: the plan is a draft and cannot run
        # until the Planner re-authors it without questions (ADR-0046).  The
        # blocked state is derived deterministically from the steps, not taken
        # from the model's status (which may be out of sync).
        blocked = [step for step in steps if step.needs_input]
        if blocked:
            plan = PlanSchema(
                step_list=steps,
                status="needs_input",
                plan_version=version,
                human_feedback_rounds=review_rounds,
                automated_plan_revisions=revisions,
            )
            update["plan"] = plan
            update["step_outputs"] = {}
            update["tool_retry_counts"] = {}
            update["step_attempt_counts"] = {}
            lines = "\n".join(
                f"- Step {step.step_number}: {question}"
                for step in blocked
                for question in step.needs_input
            )
            message = f"Plan (needs_input):\n{plan.render()}\nQuestions:\n{lines}"
            update["messages_internal"] = [
                *state.messages_internal,
                AIMessage(content=message),
            ]
            self.logger.debug(f"{update = }")
            return update

        # The plan is ready.  Human review is requested with a ``review`` step,
        # which the router pauses on when it reaches the frontier (ADR-0051);
        # there is no review status.  ``human_feedback`` has been consumed by
        # this LLM call and is cleared above.  The model's per-step statuses and
        # ``depends_on`` are used unchanged (ADR-0041).
        status: Literal["in_progress"] = "in_progress"
        plan = PlanSchema(
            step_list=steps,
            status=status,
            plan_version=version,
            human_feedback_rounds=review_rounds,
            automated_plan_revisions=revisions,
        )
        # If the Planner carried every step forward as ``done`` there is
        # nothing left to run: mark the plan complete deterministically, so the
        # graph routes to the answer instead of the step entry (ADR-0041).
        if all(step.status == "done" for step in plan.step_list):
            plan.status = "completed"
        update["plan"] = plan
        # A replan replaces the step list: clear per-step execution state so
        # stale step keys cannot merge into (or trip the retry budgets of) the
        # new plan's steps.  The LLM call above already saw the prior
        # observations and feedback when it produced this plan.
        update["step_outputs"] = {}
        update["tool_retry_counts"] = {}
        update["step_attempt_counts"] = {}
        message = f"Plan ({status}):\n{plan.render()}"
        if result.reason:
            message += f"\nReason: {result.reason}"
        update["messages_internal"] = [
            *state.messages_internal,
            AIMessage(content=message),
        ]
        self.logger.debug(f"{update = }")
        return update

    @override
    def _get_inspect(
        self, state: KleaAgentState, ctx: LLMNodeContext[Any]
    ) -> NodeStreamData:
        """Return the plan summary plus prompt and raw/processed output."""
        assert ctx.prompt is not None
        assert ctx.output is not None
        assert ctx.result is not None
        result = ctx.result
        if isinstance(result, PlannerOutput):
            summary = (
                f"Plan with {len(result.plan.step_list)} step(s), "
                f"status={result.plan.status}"
            )
        else:
            summary = "Planner output"
        return NodeStreamData(
            heading="Plan",
            summary=summary,
            details={
                "input_prompt": prompt_value_to_messages(ctx.prompt),
                "unprocessed_output": extract_llm_output_content(ctx.output),
                "processed_output": str(ctx.result),
                "tools_description": self._get_tool_descriptions(state),
            },
        )

    @override
    def _get_status(
        self, state: KleaAgentState, ctx: LLMNodeContext[Any]
    ) -> NodeStreamData | None:
        """Expose the current plan to the status pane (markdown).

        Reads the plan from ``ctx.state_updates`` -- the plan this pass just
        produced -- falling back to the pre-execution ``state.plan``.  The
        incoming state is captured at execution entry, so on a turn's first
        Planner pass it still holds the empty plan that
        :class:`InitGraphState` reset, which would render ``(no plan)``.
        """
        plan = None
        if ctx.state_updates:
            plan = ctx.state_updates.get("plan")
        if plan is None:
            plan = state.plan
        return NodeStreamData(
            heading="Plan",
            summary=f"{len(plan.step_list)} step(s); status={plan.status}",
            display=plan.render(markdown=True),
            key="plan",
            preformatted=True,
        )

    @override
    def _get_default_error_result(self, ctx: Any) -> PlannerOutput:
        """Return an empty output; ``_update_state`` marks it ``unplannable``."""
        return PlannerOutput()
