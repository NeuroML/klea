import logging
from typing import Any, ClassVar, override

from klea_utils.llm import extract_llm_output_content, prompt_value_to_messages
from klea_utils.mcp.schemas import ToolInfo
from klea_utils.nodes.abstract import NodeStreamData
from klea_utils.nodes.base import BaseLLMNode
from langchain_core.messages import AIMessage

from klea_agent.schemas import KleaAgentState, PlannerOutput, PlanSchema


class Planner(BaseLLMNode[KleaAgentState, PlannerOutput]):
    """Single entry brain for the general path (ADR-0035).

    Subsumes the former ``RouteDecision`` and ``GoalSetter``: it decides
    whether the request can be answered inline (``direct_answer``) or needs a
    plan, writes the immutable goal, and creates or revises the evolvable plan.
    ``plan.status`` carries the routing outcome (``not_needed`` |
    ``in_review`` | ``in_progress`` | ``unplannable``), so there is no separate
    route flag.

    Uses the tool descriptions generated by ``BaseLangGraph._build_tools_info``
    (``self._tools_info``) -- the orchestrator passes ``tools_info`` via
    ``set_tools_info`` before the graph is compiled.  This keeps the
    available-tools list consistent with ``ToolsPicker`` and the MCP registry.
    """

    model_type = "plan"
    model_defaults: ClassVar[dict[str, Any]] = {
        "temperature": 0.01,
        "max_output_tokens": 4096,
    }

    def __init__(
        self,
        logger: logging.Logger,
        label: str,
        llm_models: dict[str, Any],
        memory: bool = False,
    ):
        """Initialise the planner node.

        :param logger: Logger instance
        :param label: Human-readable label for UI progress display
        :param llm_models: ``{role: LLMModel}`` dict (from ``BaseLangGraph.llm_models``)
        :param memory: Whether to include recent conversation history.  The
            Planner needs prior context (follow-ups and earlier failed plans),
            so the orchestrator passes ``memory=self.memory``.
        """
        super().__init__(
            logger=logger,
            label=label,
            llm_models=llm_models,
            output_schema=PlannerOutput,
            memory=memory,
        )
        self._tools_info: dict[str, dict[str, ToolInfo]] = {}
        self._tools_description = ""

    def _get_tool_descriptions(self) -> str:
        """Return combined compact tool descriptions from ``_tools_info``.

        Uses ``ToolInfo.short_description`` (name plus docstring, no parameter
        list) so the planner prompt stays small under tiered disclosure
        (ADR-0035); the tool picker carries the full argument detail.  Falls
        back to ``description`` when a short form was not built.  Mirrors
        ``ToolsPicker._get_tool_descriptions`` but without domain filtering --
        the agent's single ``code`` domain includes all tools.
        """
        parts = [
            info.short_description or info.description or ""
            for domain_tools in self._tools_info.values()
            for info in domain_tools.values()
        ]
        return "\n\n".join(parts)

    def set_tools_info(self, tools_info: dict[str, dict[str, ToolInfo]]) -> None:
        """Set tool metadata (called by orchestrator after construction).

        Stores the per-domain ``ToolInfo`` map from ``BaseLangGraph.tools_info``
        and refreshes the cached description string.
        """
        self._tools_info = tools_info or {}
        self._tools_description = self._get_tool_descriptions()

    @override
    def _get_prompt_variables(self, state: KleaAgentState) -> dict:
        """Format prompt with the query, current plan state and tool catalogue."""
        goal_text = state.goal.goal or "(not set)"
        if state.goal.success_criteria:
            goal_text += f"\nSuccess criteria: {state.goal.success_criteria}"
        return {
            "query": state.query,
            "goal": goal_text,
            "plan": state.plan.render(),
            "human_feedback": state.human_feedback or "(none)",
            "evaluation_feedback": state.evaluation.reason or "(none)",
            "artefacts": state.artefacts,
            "discovery": state.discovery_persistent,
            "observations": state.step_outputs,
            "tools_description": self._get_tool_descriptions(),
        }

    @override
    def _update_state(
        self, result: PlannerOutput, state: KleaAgentState
    ) -> dict[str, Any]:
        """Write the goal (locked) and the plan, or the inline answer.

        Goal handling (ADR-0035): the Planner is the sole goal writer, but it
        only sets the goal while it is unset, so a replan or review revision
        cannot move the success reference.  A freshly built ``PlanSchema`` is
        written rather than mutating the previous one, and any steps already
        ``done`` in the previous plan stay ``done``.
        """
        update: dict[str, Any] = {"human_feedback": ""}

        # Goal lock: write only while unset.
        if not state.goal.goal and result.goal.goal:
            update["goal"] = result.goal
        elif (
            state.goal.goal and result.goal.goal and result.goal.goal != state.goal.goal
        ):
            self.logger.warning(
                "Planner proposed a different goal; keeping the fixed goal (ADR-0035)"
            )

        steps = result.plan.step_list
        if not steps:
            if result.direct_answer.strip():
                update["plan"] = PlanSchema(status="not_needed")
                update["message_for_user"] = result.direct_answer.strip()
            else:
                update["plan"] = PlanSchema(status="unplannable")
                update["failure_reason"] = (
                    "planner produced neither a plan nor a direct answer"
                )
                update["messages"] = [
                    *state.messages,
                    AIMessage(content=f"Planning failed: {update['failure_reason']}"),
                ]
            self.logger.debug(f"{update = }")
            return update

        # Re-apply completed steps from the previous plan (matched by number).
        done_numbers = {
            step.step_number for step in state.plan.step_list if step.status == "done"
        }
        for step in steps:
            if step.step_number in done_numbers:
                step.status = "done"

        current = len(steps)
        for index, step in enumerate(steps):
            if step.status != "done":
                current = index
                break

        # The Planner decides whether the plan needs human review before it
        # runs (``in_review``) or is ready (``in_progress``).  ``human_feedback``
        # has been consumed by this LLM call and is cleared above.
        status = "in_review" if result.plan.status == "in_review" else "in_progress"
        plan = PlanSchema(step_list=steps, status=status, current_step_index=current)
        update["plan"] = plan
        update["messages"] = [
            *state.messages,
            AIMessage(content=f"Plan ({status}):\n{plan.render()}"),
        ]
        self.logger.debug(f"{update = }")
        return update

    @override
    def _get_info(self) -> NodeStreamData:
        """Return a plan/answer summary for the inspector."""
        assert self._last_result is not None
        result = self._last_result
        if isinstance(result, PlannerOutput):
            if not result.plan.step_list and result.direct_answer.strip():
                summary = f"Answering inline ({len(result.direct_answer)} chars)"
            else:
                summary = (
                    f"Plan with {len(result.plan.step_list)} step(s), "
                    f"status={result.plan.status}"
                )
        else:
            summary = "Planner output"
        return NodeStreamData(heading="Plan", summary=summary, details={})

    @override
    def _get_status(self) -> NodeStreamData | None:
        """Expose the current plan to the status pane (markdown)."""
        state = self._last_state
        if state is None:
            return None
        plan = state.plan
        return NodeStreamData(
            heading="Plan",
            summary=f"{len(plan.step_list)} step(s); status={plan.status}",
            display=plan.render(markdown=True),
        )

    @override
    def _get_debug(self) -> NodeStreamData:
        """Return info + prompt and raw/processed output."""
        assert self._last_state is not None
        assert self._last_prompt is not None
        assert self._last_output is not None
        assert self._last_result is not None
        info = self._get_info()
        details = info.details.copy()
        details.update(
            {
                "input_prompt": prompt_value_to_messages(self._last_prompt),
                "unprocessed_output": extract_llm_output_content(self._last_output),
                "processed_output": str(self._last_result),
                "tools_description": self._get_tool_descriptions(),
            }
        )
        return NodeStreamData(
            heading=info.heading, summary=info.summary, details=details
        )

    @override
    def _get_default_error_result(self) -> PlannerOutput:
        """Return an empty output; ``_update_state`` marks it ``unplannable``."""
        return PlannerOutput()
